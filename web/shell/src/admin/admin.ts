/** A secret generated by a changeset, shown once (contract 006, `SecretShown`). */
export interface SecretShown {
  id: string;
  value: string;
  expires_at?: string | null;
}

/** A service account (contract 006, `AccountItem`): its secrets, never their value. */
export interface Account extends Record<string, unknown> {
  id: string;
  name: string;
  disabled: boolean;
  secrets: {
    id: string;
    key_id: string;
    created_at: string;
    expires_at?: string | null;
    revoked: boolean;
  }[];
}

/** An identity (contract 006, `IdentityItem`). */
export interface Identity extends Record<string, unknown> {
  id: string;
  kind: string;
  name: string;
  issuer?: string | null;
  disabled: boolean;
  revoked_after?: string | null;
}

/** An import (contract 006, `ImportDto`). */
export interface Import extends Record<string, unknown> {
  id: string;
  source: string;
  state: string;
  chunks: number;
  elements: number;
  batches: { applied: number; remaining: number };
  report: Record<string, unknown>;
  /** Why its last sort failed (`invalid-import`), until the next start (006/H18). */
  error?: ImportError;
  links: { self: string };
}

/** The problem of an import whose elements could not be sorted. */
export interface ImportError {
  type: string;
  title: string;
  detail: string | null;
  status: number;
  violations?: { rule: string; detail: string; element?: number }[];
}

/** What a write of the administration answers: a changeset applied, held or refused. */
export interface Outcome {
  kind: "applied" | "pending" | "refused";
  changeset: string | null;
  secret: SecretShown | null;
}

/** The body of a write by changeset (`ChangesetApplied`, `ChangesetPending`). */
export type Submitted = {
  changeset?: { id: string };
  state?: string;
  secret?: SecretShown | null;
};

/** The outcome of an answer of a write by changeset (201, 202, or a problem). */
export function outcomeOf(answer: Answer<Submitted>): Outcome {
  if (!answer.ok) return { kind: "refused", changeset: null, secret: null };
  const body = answer.body ?? {};
  return {
    kind: answer.status === 202 || body.state === "pending" ? "pending" : "applied",
    changeset: body.changeset?.id ?? null,
    secret: body.secret ?? null,
  };
}

/** The entries of a role typed one per line or separated by commas, without blanks. */
export function entriesOf(text: string): string[] {
  return [
    ...new Set(
      text
        .split(/[\n,]/)
        .map((e) => e.trim())
        .filter(Boolean),
    ),
  ];
}

/** The subject of a binding, as a line of text. */
export function subjectText(subject: {
  kind: string;
  id?: string | null;
  group?: string | null;
  issuer?: string | null;
}): string {
  if (subject.kind === "group") return `${subject.group ?? "?"} @ ${subject.issuer ?? "?"}`;
  if (subject.kind === "issuer") return `* @ ${subject.issuer ?? "?"}`;
  return subject.id ?? "?";
}

/** The file name of an export of the audit, dated. */
export function exportName(now: Date): string {
  return `kartenn-audit-${now.toISOString().replace(/[:.]/g, "-")}.ndjson`;
}

