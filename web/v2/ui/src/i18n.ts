export type MessageKey = keyof (typeof MESSAGES)["fr"];

const locale = ref<Locale>("fr");

/** Sets the language of the library's own words. */
export function setLocale(next: Locale): void {
  locale.value = next;
}

/** The current language, for `Intl` formats. */
export function currentLocale(): Locale {
  return locale.value;
}

/** A word of the library in the current language. */
export function t(key: MessageKey): string {
  return MESSAGES[locale.value][key];
}

/** A sentence of the library with its `{name}` holes filled. */
export function fill(key: MessageKey, values: Record<string, string | number> = {}): string {
  return t(key).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}
