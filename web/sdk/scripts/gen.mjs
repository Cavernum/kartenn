// Types of the API client, drawn from the reference contract (REQ-007-15, W8):
// `src/api/schema.d.ts` (openapi-typescript, plus the `QUERY` routes, which OpenAPI 3.1
// carries as the `x-query` extension) and `src/api/dated.ts` (the paths whose read takes
// `valid_at`). No code at run time comes from the contract.
// `node scripts/gen.mjs` writes both; `generate()` is what the freshness test compares.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { format } from "prettier";

export const CONTRACT = fileURLToPath(
  new URL("../../../specs/006-api-rest/openapi-v1.json", import.meta.url),
);
export const SCHEMA = fileURLToPath(new URL("../src/api/schema.d.ts", import.meta.url));
export const DATED = fileURLToPath(new URL("../src/api/dated.ts", import.meta.url));

const NOTICE = `// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.

// Generated by \`scripts/gen.mjs\` from specs/006-api-rest/openapi-v1.json: do not edit.
`;

const PRETTIER = { parser: "typescript", printWidth: 100 };

/** The `$ref` of a JSON body, as a `components["schemas"][…]` type. */
function refType(content) {
  const ref = content?.["application/json"]?.schema?.$ref;
  if (typeof ref !== "string") return "unknown";
  const name = ref.replace("#/components/schemas/", "");
  return `components["schemas"][${JSON.stringify(name)}]`;
}

/** The `QUERY` routes: body and answer of each `x-query` operation. */
function queries(spec) {
  const lines = Object.entries(spec.paths)
    .filter(([, item]) => item["x-query"])
    .map(([path, item]) => {
      const op = item["x-query"];
      const ok = op.responses?.["200"]?.content;
      return `  ${JSON.stringify(path)}: { body: ${refType(op.requestBody?.content)}; response: ${refType(ok)} };`;
    });
  return `\n/** Routes answering the \`QUERY\` method (REQ-006-10), from \`x-query\`. */\nexport interface queries {\n${lines.join("\n")}\n}\n`;
}

/** Paths whose \`GET\` takes \`valid_at\` (dated reads, REQ-007-24). */
function datedPaths(spec) {
  return Object.entries(spec.paths)
    .filter(([, item]) =>
      (item.get?.parameters ?? []).some((p) => p.in === "query" && p.name === "valid_at"),
    )
    .map(([path]) => path)
    .sort();
}

/** Both generated files, formatted, from a parsed contract. */
export async function generate(spec) {
  const schema = astToString(await openapiTS(structuredClone(spec))) + queries(spec);
  const dated = `/** Paths whose read is dated: the client adds \`valid_at\` and \`as_of\` from the context. */
export const DATED_PATHS: ReadonlySet<string> = new Set(${JSON.stringify(datedPaths(spec))});
`;
  return {
    schema: await format(NOTICE + schema, PRETTIER),
    dated: await format(NOTICE + dated, PRETTIER),
  };
}

export function readContract() {
  return JSON.parse(readFileSync(CONTRACT, "utf8"));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { schema, dated } = await generate(readContract());
  writeFileSync(SCHEMA, schema);
  writeFileSync(DATED, dated);
}
