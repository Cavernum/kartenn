-- Spike 004: current table + history table + system-time trigger (ADR 0017).
DROP TABLE IF EXISTS address_cur CASCADE;
DROP TABLE IF EXISTS address_cur_history CASCADE;
DROP FUNCTION IF EXISTS kartenn_versioning_dynamic() CASCADE;
DROP FUNCTION IF EXISTS address_cur_versioning() CASCADE;

CREATE TABLE address_cur (
    id            uuid NOT NULL,
    domain_id     uuid NOT NULL,
    address       inet NOT NULL,
    usage         text NOT NULL DEFAULT 'host',
    valid_period  tstzrange NOT NULL,
    sys_start     timestamptz NOT NULL,
    changeset_id  uuid NOT NULL,
    CONSTRAINT address_cur_pk PRIMARY KEY (id, valid_period WITHOUT OVERLAPS)
);
-- History: same columns plus sys_end, partitioned by month of sys_end.
CREATE TABLE address_cur_history (
    LIKE address_cur,
    sys_end timestamptz NOT NULL
) PARTITION BY RANGE (sys_end);
DO $$
DECLARE m date := date '2023-10-01';
BEGIN
    WHILE m < date '2027-01-01' LOOP
        EXECUTE format('CREATE TABLE address_cur_history_%s PARTITION OF address_cur_history
                        FOR VALUES FROM (%L) TO (%L)', to_char(m, 'YYYYMM'), m, m + interval '1 month');
        m := m + interval '1 month';
    END LOOP;
END $$;
CREATE TABLE address_cur_history_default PARTITION OF address_cur_history DEFAULT;
CREATE INDEX ON address_cur_history (id, sys_start);

-- Variant 1: generic trigger function (dynamic SQL, shared by every versioned table).
CREATE FUNCTION kartenn_versioning_dynamic() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.sys_start := now();
        RETURN NEW;
    END IF;
    EXECUTE format('INSERT INTO %I.%I SELECT ($1).*, now()', TG_TABLE_SCHEMA, TG_TABLE_NAME || '_history')
        USING OLD;
    IF TG_OP = 'UPDATE' THEN
        NEW.sys_start := now();
        RETURN NEW;
    END IF;
    RETURN OLD;
END $$;

-- Variant 2: per-table function with static SQL (generated by the migration helper).
CREATE FUNCTION address_cur_versioning() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.sys_start := now();
        RETURN NEW;
    END IF;
    INSERT INTO public.address_cur_history SELECT OLD.*, now();
    IF TG_OP = 'UPDATE' THEN
        NEW.sys_start := now();
        RETURN NEW;
    END IF;
    RETURN OLD;
END $$;
